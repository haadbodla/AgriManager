    }
    
    private fun addAnalyticsSection(document: Document, analytics: com.example.agrimanager.data.local.ExpenseBreakdown) {
        addSectionTitle(document, "EXPENSE ANALYTICS")
        
        document.add(
            Paragraph("Total Expenses: Rs. ${analytics.totalExpenses}")
                .setFontSize(14f)
                .setBold()
                .setMarginBottom(10f)
        )
        
        val table = Table(floatArrayOf(2f, 2f, 1f))
            .setWidth(UnitValue.createPercentValue(100f))
        
        table.addHeaderCell(createHeaderCell("Category"))
        table.addHeaderCell(createHeaderCell("Amount"))
        table.addHeaderCell(createHeaderCell("Percentage"))
        
        analytics.categories.forEach { category ->
            table.addCell(createDataCell(category.name))
            table.addCell(createDataCell("Rs. ${category.amount}"))
            table.addCell(createDataCell("${category.percentage.toInt()}%"))
        }
        
        document.add(table)
        document.add(Paragraph("\n"))
    }
    
    private fun addSectionTitle(document: Document, title: String) {
        document.add(
            Paragraph(title)
                .setFontSize(16f)
                .setBold()
                .setBackgroundColor(DeviceRgb(240, 240, 240))
                .setPadding(5f)
                .setMarginBottom(10f)
        )
    }
    
    private fun createHeaderCell(text: String): Cell {
        return Cell().add(Paragraph(text))
            .setBackgroundColor(DeviceRgb(66, 133, 244))
            .setFontColor(ColorConstants.WHITE)
            .setBold()
            .setTextAlignment(TextAlignment.CENTER)
            .setPadding(5f)
    }
    
    private fun createDataCell(text: String): Cell {
        return Cell().add(Paragraph(text))
            .setPadding(5f)
    }
    
    private fun createTotalCell(text: String, colspan: Int): Cell {
        return Cell(1, colspan).add(Paragraph(text))
            .setBackgroundColor(DeviceRgb(230, 230, 230))
            .setBold()
            .setPadding(5f)
    }
    
    private fun createInfoCell(label: String, value: String): Cell {
        return Cell().add(
            Paragraph("$label $value")
                .setFontSize(10f)
        ).setPadding(3f)
    }
    
    private fun addFooter(document: Document) {
        document.add(
            Paragraph("Generated by AgriManager")
                .setFontSize(8f)
                .setTextAlignment(TextAlignment.CENTER)
                .setMarginTop(20f)
        )
    }
}
