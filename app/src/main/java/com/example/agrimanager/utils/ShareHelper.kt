    /**
     * Share via WhatsApp
     */
    fun shareViaWhatsApp(
        context: Context,
        text: String,
        phoneNumber: String? = null
    ) {
        try {
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                setPackage("com.whatsapp")
                putExtra(Intent.EXTRA_TEXT, text)
                phoneNumber?.let {
                    // Format: country code + number (e.g., 92XXXXXXXXXX)
                    putExtra("jid", "$it@s.whatsapp.net")
                }
            }
            
            if (intent.resolveActivity(context.packageManager) != null) {
                context.startActivity(intent)
            } else {
                // WhatsApp not installed, fallback to regular share
                shareText(context, text, "Share via WhatsApp")
            }
        } catch (e: Exception) {
            // Fallback to regular share
            shareText(context, text, "Share")
        }
    }
    
    /**
     * Share via SMS
     */
    fun shareViaSMS(
        context: Context,
        text: String,
        phoneNumber: String? = null
    ) {
        try {
            val uri = if (phoneNumber != null) {
                Uri.parse("smsto:$phoneNumber")
            } else {
                Uri.parse("smsto:")
            }
            
            val intent = Intent(Intent.ACTION_SENDTO, uri).apply {
                putExtra("sms_body", text)
            }
            
            context.startActivity(intent)
        } catch (e: Exception) {
            // Fallback to regular share
            shareText(context, text, "Share via SMS")
        }
    }
    
    /**
     * Generic text sharing (shows share sheet)
     */
    fun shareText(
        context: Context,
        text: String,
        title: String = "Share"
    ) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, text)
            putExtra(Intent.EXTRA_SUBJECT, title)
        }
        
        val chooser = Intent.createChooser(intent, title)
        context.startActivity(chooser)
    }
    
    /**
     * Export ledger to CSV file and share
     */
    fun exportAndShareCSV(
        context: Context,
        fileName: String,
        headers: List<String>,
        rows: List<List<String>>
    ) {
        try {
            val file = File(context.cacheDir, "$fileName.csv")
            FileWriter(file).use { writer ->
                // Write headers
                writer.append(headers.joinToString(","))
                writer.append("\n")
                
                // Write rows
                rows.forEach { row ->
                    writer.append(row.joinToString(","))
                    writer.append("\n")
                }
            }
            
            // Share the file
            val uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )
            
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "text/csv"
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            
            context.startActivity(Intent.createChooser(intent, "Export CSV"))
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }
    
    /**
     * Generate PDF receipt for salary transactions using PdfExportManager
     */
    fun generatePDFReceipt(
        context: Context,
        employeeName: String,
        transactionType: String,
        amount: Double,
        date: Long
    ) {
        try {
            // Determine transaction type
            val isCredit = transactionType.contains("Salary", ignoreCase = true) || 
                          transactionType.contains("Payment", ignoreCase = true)
            
            // Create a minimal ExportData with just this transaction
            val exportData = com.example.agrimanager.data.models.ExportData(
                farmName = "AgriManager",
                exportDate = System.currentTimeMillis(),
                generatedBy = employeeName,
                userRole = "Receipt",
                dateRange = SimpleDateFormat("dd MMM yyyy", Locale.getDefault()).format(Date(date)),
                machines = null,
                fuelLogs = null,
                employees = null,
                transactions = listOf(
                    com.example.agrimanager.data.models.TransactionWithEmployee(
                        id = 0,
                        employeeId = 0,
                        employeeName = employeeName,
                        amount = amount,
                        type = if (isCredit) "CREDIT" else "DEBIT",
                        timestamp = date
                    )
                ),
                locations = null,
                bills = null,
                inventoryItems = null,
                stockTransactions = null,
                laborLogs = null,
                maintenanceLogs = null,
                dairyLogs = null,
                analytics = null
            )
            
            // Use PdfExportManager to generate PDF
            val pdfExportManager = com.example.agrimanager.utils.PdfExportManager(context)
            val result = pdfExportManager.generatePdf(exportData)
            
            if (result.isSuccess) {
                val file = result.getOrNull()!!
                
                // Share the generated PDF
                val uri = FileProvider.getUriForFile(
                    context,
                    "${context.packageName}.provider",
                    file
                )
                
                val intent = Intent(Intent.ACTION_SEND).apply {
                    type = "application/pdf"
                    putExtra(Intent.EXTRA_STREAM, uri)
                    putExtra(Intent.EXTRA_SUBJECT, "$transactionType - $employeeName")
                    addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                }
                
                context.startActivity(Intent.createChooser(intent, "Share Receipt PDF"))
            } else {
                // If PDF generation fails, fallback to text sharing
                shareTransactionReceipt(context, employeeName, transactionType, amount, date)
            }
        } catch (e: Exception) {
            e.printStackTrace()
            // Fallback to text sharing on error
            shareTransactionReceipt(context, employeeName, transactionType, amount, date)
        }
    }
