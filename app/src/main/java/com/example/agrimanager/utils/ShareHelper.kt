    /**
     * Share transaction receipt as text
     */
    fun shareTransactionReceipt(
        context: Context,
        employeeName: String,
        transactionType: String,
        amount: Double,
        date: Long,
        balance: Double? = null
    ) {
        val dateFormat = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault())
        val formattedDate = dateFormat.format(Date(date))
        
        val receiptText = buildString {
            appendLine("━━━━━━━━━━━━━━━━━━━━━━━━")
            appendLine("📄 AgriManager Receipt")
            appendLine("━━━━━━━━━━━━━━━━━━━━━━━━")
            appendLine()
            appendLine("Employee: $employeeName")
            appendLine("Type: $transactionType")
            appendLine("Amount: Rs ${amount.toInt()}")
            appendLine("Date: $formattedDate")
            balance?.let {
                appendLine()
                appendLine("Current Balance: Rs ${it.toInt()}")
            }
            appendLine()
            appendLine("━━━━━━━━━━━━━━━━━━━━━━━━")
            appendLine("Generated by AgriManager")
        }
        
        shareText(context, receiptText, "Transaction Receipt")
    }
    
